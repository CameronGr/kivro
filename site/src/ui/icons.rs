use leptos::prelude::*;

use crate::cn;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct IconData {
    pub body: &'static str,
}

impl IconData {
    pub const fn new(body: &'static str) -> Self {
        Self { body }
    }
}

#[component]
pub fn Icon(
    icon: IconData,
    #[prop(into, optional)] class: String,
    #[prop(default = 2.0)] stroke_width: f32,
    #[prop(into, optional)] label: Option<String>,
) -> impl IntoView {
    let labelled = label.is_some();
    view! {
        <svg
            xmlns="http://www.w3.org/2000/svg"
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            stroke-width=stroke_width
            stroke-linecap="round"
            stroke-linejoin="round"
            class=cn!("shrink-0", class)
            role=move || if labelled { "img" } else { "presentation" }
            aria-hidden=move || (!labelled).then_some("true")
            aria-label=label
            inner_html=icon.body
        ></svg>
    }
}

macro_rules! icons {
    ($($(#[$meta:meta])* $name:ident => $body:literal),* $(,)?) => {
        $(
            $(#[$meta])*
            pub const $name: IconData = IconData::new($body);
        )*
        pub const ALL: &[(&str, IconData)] = &[$((stringify!($name), $name)),*];
    };
}

